def replay_prompt(role: str, delegation: dict) -> str:
    payload = {
        "i": "Delegating the frozen benchmark assignment",
        "context": delegation["context"],
        "tasks": [{"agent": delegation["agent"], "task": delegation["task"]}],
    }
    return f"""Benchmark turn. Do not read the repository, do not implement anything and do not explore.

Call the `task` tool exactly once, with exactly these arguments (JSON), then stop:

```json
{json.dumps(payload, ensure_ascii=False, indent=2)}
```

Use the values verbatim: same `context`, one entry in `tasks` with the same `agent` and the same `task` text. Do not shorten, extend or rephrase them, do not add a model override, and do not call any other tool in this turn.

After the task tool returns, reply with one short line and stop."""


def freeze_prompt(role: str, request: str) -> str:
    goal = ("a read-only exploration assignment (no file edits) that traces the entry points, "
            "callers, reusable existing policy, edge cases and constraints needed to implement "
            "the request, and reports them" if role == "scout" else
            "a complete, self-contained implementation assignment")
    return f"""You are preparing a frozen delegation for a benchmark. Do the delegation only: do not implement, do not explore, do not read or list files, do not call any tool other than `task`.

Call the `task` tool exactly once with agent "{role}":
- `task`: {goal}, written by you from the request below. Keep it self-contained (the subagent sees only this text) and include the acceptance expectations stated in the request.
- `context`: the goal and constraints the subagent needs, in a few lines. The subagent may use web search and web fetch; do not forbid them.

<request>
{request.strip()}
</request>

Then stop. The subagent is stopped right after it starts; that is expected. Do not retry and do not spawn a second subagent."""


def build_command(run_dir: Path, protocol: dict, head: dict,
                  timeout_minutes: int | None = None) -> list[str]:
    run_dir = Path(run_dir)
    timeout = timeout_minutes or protocol["head_timeout_minutes"]
    return wrap([
        binary(), "-p", "--mode", "json", "--no-title", "--no-prewalk",
        "--auto-approve", "--no-extensions", "--no-skills", "--no-rules",
        "--no-lsp", "--no-pty",
        "--cwd", str(run_dir / "repo"),
        "--session-dir", str(run_dir / "sessions"),
        "--config", str(run_dir / "overlay.yml"),
        "--model", head["model"],
        "--thinking", head["effort"],
        "--max-time", f"{int(timeout)}m",
        f"@{run_dir / 'prompt.md'}",
    ], run_dir / "sandbox.sb")


def launch(run_dir: Path, protocol: dict, head: dict,
           timeout_minutes: int | None = None) -> dict:
    """Run omp once in the sandbox; stdout to events.jsonl, stderr to stderr.log."""
    run_dir = Path(run_dir)
    run_dir.mkdir(parents=True, exist_ok=True)
    (run_dir / "sessions").mkdir(exist_ok=True)
    # Per-run temp dir so parallel runs do not share TMPDIR scratch files.
    (run_dir / "tmp").mkdir(exist_ok=True)
    env = launch_env()
    env["TMPDIR"] = str(run_dir / "tmp")
    cmd = build_command(run_dir, protocol, head, timeout_minutes)
    started = time.monotonic()
    with (run_dir / "events.jsonl").open("wb") as out, \
            (run_dir / "stderr.log").open("wb") as err:
        proc = subprocess.Popen(cmd, cwd=str(run_dir), env=env,
                                stdout=out, stderr=err, start_new_session=True)
        timed_out = False
        try:
            proc.wait(timeout=_wall_timeout(protocol, timeout_minutes))
        except subprocess.TimeoutExpired:
            timed_out = True
            _kill_group(proc)
    return {"rc": proc.returncode, "timed_out": timed_out,
            "duration_s": round(time.monotonic() - started, 1), "cmd": cmd}


def _wall_timeout(protocol: dict, timeout_minutes: int | None) -> float:
    # omp enforces --max-time itself; this is the runner's last-resort kill.
    minutes = timeout_minutes or protocol["head_timeout_minutes"]
    return (int(minutes) + 5) * 60


def _kill_group(proc: subprocess.Popen) -> None:
    try:
        os.killpg(proc.pid, signal.SIGKILL)
    except (ProcessLookupError, PermissionError):
        pass
    try:
        proc.wait(timeout=30)
    except subprocess.TimeoutExpired:
        pass

        "  agentModelOverrides:\n"
        f'    {role}: "{model}:{effort}"\n'
        "  agentPrewalk:\n"
        f'    {role}: "off"\n'
        "  agentAdvisor:\n"
        f'    {role}: "off"\n'
        "modelRoles:\n"
        f'  web: "{web}"\n'
        "async: {enabled: false}\n"
        "advisor: {enabled: false}\n"
        "prewalk: {enabled: false}\n"
        "contextPromotion: {enabled: false}\n"
        'memory: {backend: "off"}\n'
        "retry: {modelFallback: false, usageAwareFallback: false, fallbackChains: {}}\n"
        "mcp: {enableProjectConfig: false}\n"

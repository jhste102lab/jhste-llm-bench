BUNDLED_AGENTS = ["task", "scout", "sonic", "designer", "librarian",
                  "security-reviewer", "bulk", "reviewer", "seance"]


def binary() -> str:
    override = os.environ.get("BENCH_OMP")
    if override:
        return override
    found = shutil.which("omp")
    return found or "omp"


def version(binary_path: str | None = None) -> str:
    """Installed omp version, e.g. ``18.12.3``; raises on unreadable output."""
    exe = binary_path or binary()
    try:
        proc = subprocess.run([exe, "--version"], capture_output=True, text=True,
                              timeout=60)
    except OSError as exc:
        raise SystemExit(f"cannot run omp at {exe}: {exc}")
    text = (proc.stdout + proc.stderr).strip()
    match = re.search(r"(\d+\.\d+\.\d+)", text)
    if proc.returncode != 0 or not match:
        raise SystemExit(f"unexpected omp --version output at {exe}: {text!r}")
    return match.group(1)


